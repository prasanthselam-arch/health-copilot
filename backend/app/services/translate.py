"""Cached translation of short patient-facing strings (insights, tips, copilot notes), keeping every number.

English is generated by code; other languages are translated once per content and cached in Summary. If the model is
unavailable, or the translation changes a number, the English text is returned instead.
"""

import hashlib
import json
import logging

from pydantic import BaseModel
from sqlmodel import Session, select

from app.models.tables import Summary
from app.pipeline import llm
from app.services.safety import LANGUAGES, numbers_preserved

log = logging.getLogger(__name__)

SYSTEM = """You translate short patient-facing health texts from English into {language}.
- Natural, simple, everyday {language} that an elderly patient understands; avoid overly formal words.
- Keep every number, unit, date, test name abbreviation (HbA1c, LDL, TSH...) and medicine name exactly as written.
- Return exactly one translation per input item, in the same order. Do not add or drop information."""


class Strings(BaseModel):
    items: list[str]


def translate_strings(db: Session, patient_id: str, scope: str, strings: list[str], lang: str) -> tuple[list[str], bool]:
    if lang == "en" or lang not in LANGUAGES or not strings:
        return strings, lang == "en"
    h = hashlib.sha256(json.dumps(["t1", strings], ensure_ascii=False).encode()).hexdigest()[:24]
    row = db.exec(select(Summary).where(Summary.patient_id == patient_id, Summary.scope == scope, Summary.language == lang,
                                        Summary.source_hash == h)).first()
    if row:
        return row.content["items"], True
    try:
        out: Strings = llm.parse("fast", SYSTEM.format(language=LANGUAGES[lang]),
                                 "ITEMS (JSON list):\n" + json.dumps(strings, ensure_ascii=False), Strings,
                                 interactive=True).parsed
    except Exception as e:  # noqa: BLE001
        log.warning("translation to %s unavailable: %s", lang, str(e)[:200])
        return strings, False
    if len(out.items) != len(strings):
        return strings, False
    items = [t if numbers_preserved(s, t) else s for s, t in zip(strings, out.items)]
    db.add(Summary(patient_id=patient_id, scope=scope, language=lang, source_hash=h, content={"items": items}))
    db.commit()
    return items, True
